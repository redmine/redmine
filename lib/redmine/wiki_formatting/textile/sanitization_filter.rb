module Redmine
  module WikiFormatting
    module Textile
      # Sanitizes the HTML generated by the Textile formatter
      class SanitizationFilter < Redmine::WikiFormatting::SanitizationFilter
        ALLOWED_CLASS_RE = /\A(wiki-class-\S+|external|email|footnote)\z/
        ALLOWED_ID_RE = /\A(wiki-id-\S+|fn\d+)\z/

        # Same properties as the ones accepted by RedCloth3::STYLES_RE
        STYLE_PROPERTY_RE = /\A(color|(min-|max-)?(width|height)|border|background|padding|margin|font|text|float)(-[a-z]+)*\z/
        STYLE_PROPERTIES =
          (Sanitize::Config::RELAXED[:css][:properties].grep(STYLE_PROPERTY_RE) + %w[vertical-align]).freeze

        private

        def default_allowlist
          allowlist = super
          allowlist[:attributes][:all] += %w[class id]
          allowlist[:css][:properties] |= STYLE_PROPERTIES
          allowlist
        end

        def add_transformers
          super
          allowlist[:transformers].push method(:remove_disallowed_classes_and_ids)
        end

        def remove_disallowed_classes_and_ids(env)
          node = env[:node]
          return unless node.element?

          # The class of <code> holds the language for syntax highlighting
          if node['class'] && node.name != 'code'
            allowed_classes = node['class'].split.grep(ALLOWED_CLASS_RE)
            if allowed_classes.any?
              node['class'] = allowed_classes.join(' ')
            else
              node.remove_attribute('class')
            end
          end

          node.remove_attribute('id') if node['id'] && !ALLOWED_ID_RE.match?(node['id'])
        end
      end
    end
  end
end
